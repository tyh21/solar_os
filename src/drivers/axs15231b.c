/* Register access opcodes of the AXS15231B QSPI command protocol. */
#define AXS_OPCODE_WRITE_CMD 0x02ULL
#define AXS_OPCODE_READ_CMD 0x0BU
#define AXS_OPCODE_WRITE_COLOR 0x32ULL

