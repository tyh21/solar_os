static inline int axs_write_opcode(uint8_t cmd)
{
    return (int)((AXS_OPCODE_WRITE_CMD << 24) | ((uint32_t)cmd << 8));
}

esp_err_t axs15231b_bus_init(spi_host_device_t host,
                             const axs15231b_bus_pins_t *pins,
                             size_t max_transfer_sz)
{
    if (pins == NULL || pins->sclk_pin < 0 || pins->data0_pin < 0 ||
        pins->data1_pin < 0 || pins->data2_pin < 0 || pins->data3_pin < 0) {
        return ESP_ERR_INVALID_ARG;
    }
    const spi_bus_config_t bus_config = {
        .sclk_io_num = pins->sclk_pin,
        .data0_io_num = pins->data0_pin,
        .data1_io_num = pins->data1_pin,
        .data2_io_num = pins->data2_pin,
        .data3_io_num = pins->data3_pin,
        .max_transfer_sz = (int)max_transfer_sz,
    };
    return spi_bus_initialize(host, &bus_config, SPI_DMA_CH_AUTO);
}

esp_err_t axs15231b_panel_io_create(spi_host_device_t host,
                                    int cs_pin,
                                    uint32_t clock_hz,
                                    esp_lcd_panel_io_handle_t *panel_io)
{
    if (panel_io == NULL) {
        return ESP_ERR_INVALID_ARG;
    }
    const esp_lcd_panel_io_spi_config_t io_config = {
        .cs_gpio_num = cs_pin,
        .dc_gpio_num = -1,
        .spi_mode = 3,
        .pclk_hz = clock_hz > 0 ? clock_hz : 40U * 1000U * 1000U,
        .trans_queue_depth = 10,
        .lcd_cmd_bits = 32,
        .lcd_param_bits = 8,
        .flags = {
            .quad_mode = true,
        },
    };
    return esp_lcd_new_panel_io_spi((esp_lcd_spi_bus_handle_t)host,
                                    &io_config, panel_io);
}

esp_err_t axs15231b_panel_init_sequence(esp_lcd_panel_io_handle_t panel_io)
{
    if (panel_io == NULL) {
        return ESP_ERR_INVALID_ARG;
    }

    ESP_RETURN_ON_ERROR(
        esp_lcd_panel_io_tx_param(panel_io, axs_write_opcode(AXS_CMD_SWRESET),
                                  NULL, 0),
        TAG, "software reset failed");
    vTaskDelay(pdMS_TO_TICKS(120));

    /* The reference component (esp_lcd_axs15231b) sends SLPOUT/MADCTL/COLMOD
     * before the vendor table; the panel needs COLMOD=0x55 for RGB565. */
    ESP_RETURN_ON_ERROR(
        esp_lcd_panel_io_tx_param(panel_io, axs_write_opcode(AXS_CMD_SLPOUT),
                                  NULL, 0),
        TAG, "sleep exit failed");
    vTaskDelay(pdMS_TO_TICKS(100));
    const uint8_t madctl = 0x00; /* RGB element order, no mirror/swap */
    ESP_RETURN_ON_ERROR(
        esp_lcd_panel_io_tx_param(panel_io, axs_write_opcode(AXS_CMD_MADCTL),
                                  &madctl, sizeof(madctl)),
        TAG, "madctl failed");
    const uint8_t colmod = 0x55; /* 16 bits per pixel, RGB565 */
    ESP_RETURN_ON_ERROR(
        esp_lcd_panel_io_tx_param(panel_io, axs_write_opcode(AXS_CMD_COLMOD),
                                  &colmod, sizeof(colmod)),
        TAG, "colmod failed");

    for (size_t i = 0; i < sizeof(axs15231b_init_cmds) /
                                    sizeof(axs15231b_init_cmds[0]);
         i++) {
        const axs15231b_init_cmd_t *entry = &axs15231b_init_cmds[i];
        esp_err_t err = esp_lcd_panel_io_tx_param(
            panel_io, axs_write_opcode((uint8_t)entry->cmd), entry->data,
            entry->data_bytes);
        ESP_RETURN_ON_ERROR(err, TAG, "init command 0x%02x failed",
                            (unsigned)entry->cmd);
        if (entry->delay_ms > 0) {
            vTaskDelay(pdMS_TO_TICKS(entry->delay_ms));
        }
    }
    return ESP_OK;
}

void axs15231b_bus_free(spi_host_device_t host,
                        esp_lcd_panel_io_handle_t panel_io)
{
    if (panel_io != NULL) {
        esp_lcd_panel_io_del(panel_io);
    }
    spi_bus_free(host);
}
